/*
 * CRT-based 512-pt NTT for Raccoon-128.
 *
 * Raccoon's modulus q = 549824583172097 = p1 * p2 is composite, so
 * we cannot run a single NTT mod q.  Instead we work in the CRT domain:
 *
 *   x mod q  <==>  (x mod p1,  x mod p2)
 *
 * Both p1 = 33292289 and p2 = 16515073 are NTT-friendly:
 *   p1 - 1 divisible by 1024  =>  supports 512-pt negacyclic NTT
 *   p2 - 1 divisible by 1024  =>  supports 512-pt negacyclic NTT
 *
 * Layout of poly_t in NTT domain:
 *   coeffs[i]       holds the CRT pair packed as:
 *     low  32 bits : coefficient mod p1
 *     high 32 bits : coefficient mod p2
 *
 * This packing lets us keep a single poly_t struct while carrying both
 * CRT components.  Coefficient-domain polys store the full int64_t value
 * in coeffs[i] (reduced into [0, q-1]).
 */

