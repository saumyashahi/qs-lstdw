/* ------------------------------------------------------------------ */
/* Arithmetic helpers                                                  */
/* ------------------------------------------------------------------ */

static inline int32_t mulmod_p1(int32_t a, int32_t b)
{
    return (int32_t)(((int64_t)a * b) % P1);
}

static inline int32_t mulmod_p2(int32_t a, int32_t b)
{
    return (int32_t)(((int64_t)a * b) % P2);
}

static inline int32_t addmod_p1(int32_t a, int32_t b)
{
    int32_t r = a + b;
    if (r >= P1) r -= P1;
    return r;
}

static inline int32_t submod_p1(int32_t a, int32_t b)
{
    int32_t r = a - b;
    if (r < 0) r += P1;
    return r;
}

static inline int32_t addmod_p2(int32_t a, int32_t b)
{
    int32_t r = a + b;
    if (r >= P2) r -= P2;
    return r;
}

static inline int32_t submod_p2(int32_t a, int32_t b)
{
    int32_t r = a - b;
    if (r < 0) r += P2;
    return r;
}

/* ------------------------------------------------------------------ */
/* CRT split / merge                                                   */
/* ------------------------------------------------------------------ */

/*
 * Split a coefficient x in [0, q-1] into (x mod p1, x mod p2).
 * We pack them into int64_t:  low word = x mod p1,  high word = x mod p2.
 */
static inline int64_t crt_split(int64_t x)
{
    int64_t x1 = x % P1;
    int64_t x2 = x % P2;
    if (x1 < 0) x1 += P1;
    if (x2 < 0) x2 += P2;
    return (x2 << 32) | (uint32_t)x1;
}

/*
 * Merge CRT pair (a1, a2) back to a value in [0, q-1] via Garner:
 *   t  = (a2 - a1) * p1_inv_p2  mod p2
 *   x  = a1 + t * p1
 */
static inline int64_t crt_merge(int32_t a1, int32_t a2)
{
    int64_t diff = ((int64_t)a2 - a1 % P2 + P2) % P2;
    int64_t t    = (diff * P1_INV_P2) % P2;
    int64_t x    = (int64_t)a1 + t * RACCOON_P1;
    return x;  /* in [0, q-1] */
}

/* Extract p1 component from packed NTT coefficient */
static inline int32_t get_p1(int64_t packed) { return (int32_t)(packed & 0xFFFFFFFFLL); }
/* Extract p2 component from packed NTT coefficient */
static inline int32_t get_p2(int64_t packed) { return (int32_t)((uint64_t)packed >> 32); }
/* Pack (a1, a2) */
static inline int64_t pack(int32_t a1, int32_t a2) { return ((int64_t)(uint32_t)a2 << 32) | (uint32_t)a1; }

/* ------------------------------------------------------------------ */
/* Forward NTT (in-place, Cooley-Tukey)                               */
/*                                                                    */
/* Input:  coefficient domain poly_t (int64_t in [0, q-1])           */
/* Output: NTT domain poly_t — each coeffs[i] packed as              */
/*         (coeffs[i] mod p2) << 32  |  (coeffs[i] mod p1)          */
/* ------------------------------------------------------------------ */
void poly_ntt(poly_t *a)
{
    /* Step 1: split into CRT components */
    int32_t a1[NTT_N], a2[NTT_N];
    for (int i = 0; i < NTT_N; i++) {
        int64_t x = a->coeffs[i];
        a1[i] = (int32_t)(x % P1);
        a2[i] = (int32_t)(x % P2);
        if (a1[i] < 0) a1[i] += P1;
        if (a2[i] < 0) a2[i] += P2;
    }

    /* Step 2: forward NTT mod p1 */
    {
        int k = 1;
        for (int len = NTT_N/2; len > 0; len >>= 1) {
            for (int start = 0; start < NTT_N; start += 2*len) {
                int32_t zeta = zetas_p1[k++];
                for (int j = start; j < start+len; j++) {
                    int32_t t      = mulmod_p1(zeta, a1[j+len]);
                    a1[j+len]      = submod_p1(a1[j], t);
                    a1[j]          = addmod_p1(a1[j], t);
                }
            }
        }
    }

    /* Step 3: forward NTT mod p2 */
    {
        int k = 1;
        for (int len = NTT_N/2; len > 0; len >>= 1) {
            for (int start = 0; start < NTT_N; start += 2*len) {
                int32_t zeta = zetas_p2[k++];
                for (int j = start; j < start+len; j++) {
                    int32_t t      = mulmod_p2(zeta, a2[j+len]);
                    a2[j+len]      = submod_p2(a2[j], t);
                    a2[j]          = addmod_p2(a2[j], t);
                }
            }
        }
    }

    /* Step 4: pack results */
    for (int i = 0; i < NTT_N; i++)
        a->coeffs[i] = pack(a1[i], a2[i]);
}

/* ------------------------------------------------------------------ */
/* Inverse NTT (in-place, Gentleman-Sande)                            */
/*                                                                    */
/* Input:  packed NTT domain poly_t                                   */
/* Output: coefficient domain poly_t in [0, q-1]                     */
/* ------------------------------------------------------------------ */
void poly_invntt(poly_t *a)
{
    int32_t a1[NTT_N], a2[NTT_N];
    for (int i = 0; i < NTT_N; i++) {
        a1[i] = get_p1(a->coeffs[i]);
        a2[i] = get_p2(a->coeffs[i]);
    }

    /* Inverse NTT mod p1 */
    {
        int k = NTT_N - 1;
        for (int len = 1; len < NTT_N; len <<= 1) {
            for (int start = 0; start < NTT_N; start += 2*len) {
                int32_t zeta = zetas_p1[k--];
                for (int j = start; j < start+len; j++) {
                    int32_t t  = a1[j];
                    a1[j]      = addmod_p1(t, a1[j+len]);
                    a1[j+len]  = mulmod_p1(zeta, submod_p1(t, a1[j+len]));
                }
            }
        }
        /* Scale by n^{-1} mod p1 */
        for (int i = 0; i < NTT_N; i++)
            a1[i] = mulmod_p1(a1[i], N_INV_P1);
    }

    /* Inverse NTT mod p2 */
    {
        int k = NTT_N - 1;
        for (int len = 1; len < NTT_N; len <<= 1) {
            for (int start = 0; start < NTT_N; start += 2*len) {
                int32_t zeta = zetas_p2[k--];
                for (int j = start; j < start+len; j++) {
                    int32_t t  = a2[j];
                    a2[j]      = addmod_p2(t, a2[j+len]);
                    a2[j+len]  = mulmod_p2(zeta, submod_p2(t, a2[j+len]));
                }
            }
        }
        /* Scale by n^{-1} mod p2 */
        for (int i = 0; i < NTT_N; i++)
            a2[i] = mulmod_p2(a2[i], N_INV_P2);
    }

    /* Garner CRT merge back to [0, q-1] */
    for (int i = 0; i < NTT_N; i++)
        a->coeffs[i] = crt_merge(a1[i], a2[i]);
}

/* ------------------------------------------------------------------ */
/* Pointwise multiplication in NTT domain                             */
/* Both inputs MUST be in NTT domain (output of poly_ntt).            */
/* ------------------------------------------------------------------ */
void poly_pointwise_mul(poly_t *r, const poly_t *a, const poly_t *b)
{
    for (int i = 0; i < NTT_N; i++) {
        int32_t a1 = get_p1(a->coeffs[i]);
        int32_t a2 = get_p2(a->coeffs[i]);
        int32_t b1 = get_p1(b->coeffs[i]);
        int32_t b2 = get_p2(b->coeffs[i]);
        r->coeffs[i] = pack(mulmod_p1(a1, b1), mulmod_p2(a2, b2));
    }
}

